/**
 * ตัดศูนย์ท้ายทศนิยมทิ้ง
 *
 * ปริมาณวัตถุดิบเป็นเศษส่วนบ่อย — 0.10 ขวด อ่านยากกว่า 0.1 ขวด
 * และ 2.000 กก. ก็ควรเป็น 2 กก. ตัดที่ 3 ตำแหน่งเพราะเศษที่ละเอียดกว่านั้น
 * ไม่มีความหมายในครัว
 */
export function trim(value) {
  return Number(Number(value).toFixed(3)).toString()
}
